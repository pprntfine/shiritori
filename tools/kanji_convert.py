def conv(t):
    def tok(m):
        w=m.group(0)
        if w in EXACT: return EXACT[w]
        for a,b in PRE:
            if w.startswith(a):
                if a=='きれ' and w.startswith('きれい'): return w
                return b+w[len(a):]
        return w
    t=re.sub(r'(?:(?<=^)|(?<=[ 「（(・／、。！？…\n『]))[぀-ゟー]+(?:サーバー)?',tok,t)
    t=re.sub(r'(?<=['+JP+'、。！？」』）…〜])  ?(?=['+JP+'「『（])','',t)
    return t
def process(src,lo,hi):
    out=[];n=0
    for i,ln in enumerate(src.split('\n'),1):
        if lo<=i<=hi or len(ln)>20000:
            out.append(ln); continue
        if not re.search('[\u3040-\u309f]',ln):
            out.append(ln); continue
        code=ln.lstrip()
        if code.startswith('/*') or code.startswith('//') or code.startswith('*'):
            out.append(ln); continue
        def lit(m):
            q=m.group(1); body=m.group(2)
            if not re.search('[぀-ゟ]',body): return m.group(0)
            return q+conv(body)+q
        new=re.sub(r"(['\"])((?:(?!\1)[^\\\n]|\\.)*)\1",lit,ln)
        new=re.sub(r'>([^<>\n\'"]*[぀-ゟ][^<>\n\'"]*)<',lambda m:'>'+conv(m.group(1))+'<',new)
        if new!=ln: n+=1
        out.append(new)
    return '\n'.join(out),n
